import { severityRank, type Config, type Language, type Severity } from './config.js';
import type { FileDiff, SelectedDiff } from './diff.js';
import type { Finding } from './review.js';

// Everything the model writes is treated as untrusted before it reaches GitHub:
// a prompt-injected diff could try to make the bot ping people, embed tracking
// images (data exfiltration through image URLs) or post phishing links.

export const MARKER = 'ai-code-review';

export function sanitize(text: string, max = 3000): string {
  return text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<\/?[a-z][^>]*>/gi, '') // raw HTML
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1') // images → alt text
    .replace(/\[([^\]]+)\]\((?:[^)]*)\)/g, '$1') // links → text
    .replace(/\bhttps?:\/\/\S+/gi, (url) => '`' + url.replace(/`/g, '') + '`') // bare URLs → inert code
    .replace(/(^|[^\w`])@([a-z0-9-]+)/gi, '$1@​$2') // @mentions → no ping
    .replace(/(^|\s)#(\d+)/g, '$1#​$2') // issue cross-references → no backlink spam
    .slice(0, max)
    .trim();
}

const fence = (code: string) => {
  const ticks = code.includes('```') ? '````' : '```';
  return `${ticks}suggestion\n${code.replace(/\n$/, '')}\n${ticks}`;
};

const ICON: Record<Severity, string> = { critical: '🔴', high: '🟠', medium: '🟡', low: '🔵' };

const T = {
  en: {
    heading: 'AI code review',
    noFindings: 'No issues found in the reviewed changes.',
    outside: 'Findings outside the diff',
    coverage: (n: number, m: number) => `Reviewed ${n} file(s)${m ? `, skipped ${m}` : ''}.`,
    skipped: 'Not reviewed',
    reasons: { excluded: 'excluded by filters', 'no-patch': 'binary or too large', budget: 'over the diff budget', removed: 'deleted' },
    refused: 'The model declined to review this change, so no findings were posted.',
    footer: (model: string, cost: string) => `Generated by ${model}${cost}. AI reviews can be wrong: treat findings as suggestions.`,
  },
  'pt-BR': {
    heading: 'Revisão de código por IA',
    noFindings: 'Nenhum problema encontrado nas mudanças revisadas.',
    outside: 'Achados fora do diff',
    coverage: (n: number, m: number) => `${n} arquivo(s) revisado(s)${m ? `, ${m} ignorado(s)` : ''}.`,
    skipped: 'Não revisados',
    reasons: { excluded: 'filtrado', 'no-patch': 'binário ou grande demais', budget: 'acima do limite do diff', removed: 'removido' },
    refused: 'O modelo recusou revisar esta mudança, então nenhum achado foi publicado.',
    footer: (model: string, cost: string) => `Gerado por ${model}${cost}. Revisões por IA podem errar: trate os achados como sugestões.`,
  },
} satisfies Record<Language, unknown>;

export interface ReviewComment {
  path: string;
  line: number;
  side: 'RIGHT';
  body: string;
}

export interface Placement {
  inline: ReviewComment[];
  outside: Finding[];
  kept: Finding[];
}

/** Filters by severity, caps the count and keeps only comments GitHub will accept. */
export function placeFindings(findings: Finding[], files: FileDiff[], config: Config): Placement {
  const byPath = new Map(files.map((f) => [f.path, f]));
  const kept = findings
    .filter((f) => severityRank(f.severity) >= severityRank(config.minSeverity))
    .sort((a, b) => severityRank(b.severity) - severityRank(a.severity))
    .slice(0, config.maxFindings);

  const inline: ReviewComment[] = [];
  const outside: Finding[] = [];
  for (const f of kept) {
    const file = byPath.get(f.path);
    if (!file || !file.commentable.has(f.line)) { outside.push(f); continue; }
    const suggestion = f.suggestion.trim() && file.added.has(f.line) ? `\n\n${fence(sanitize(f.suggestion, 3000))}` : '';
    inline.push({
      path: f.path,
      line: f.line,
      side: 'RIGHT',
      body: `${ICON[f.severity]} **${sanitize(f.title, 200)}** · \`${f.severity}\` · \`${f.category}\`\n\n${sanitize(f.body)}${suggestion}`,
    });
  }
  return { inline, outside, kept };
}

export function summaryBody(args: {
  summary: string | null;
  placement: Placement | null;
  selection: SelectedDiff;
  config: Config;
  model: string;
  costUsd: number | null;
  headSha: string;
  refused?: boolean;
}): string {
  const t = T[args.config.language];
  const lines = [`### ${t.heading}`, ''];
  if (args.refused) lines.push(t.refused, '');
  if (args.summary) lines.push(sanitize(args.summary, 2000), '');
  if (args.placement && args.placement.kept.length === 0 && !args.refused) lines.push(t.noFindings, '');
  if (args.placement && args.placement.outside.length > 0) {
    lines.push(`**${t.outside}**`, '');
    for (const f of args.placement.outside) {
      lines.push(`- ${ICON[f.severity]} \`${sanitize(f.path, 200)}:${f.line}\` **${sanitize(f.title, 200)}** — ${sanitize(f.body, 600)}`);
    }
    lines.push('');
  }
  lines.push(t.coverage(args.selection.files.length, args.selection.skipped.length));
  if (args.selection.skipped.length > 0) {
    const shown = args.selection.skipped.slice(0, 30).map((s) => `\`${sanitize(s.path, 200)}\` (${t.reasons[s.reason]})`);
    lines.push('', `<details><summary>${t.skipped}</summary>\n\n${shown.join('<br>\n')}${args.selection.skipped.length > 30 ? '<br>\n…' : ''}\n</details>`);
  }
  const cost = args.costUsd !== null ? ` · ~US$ ${args.costUsd.toFixed(4)}` : '';
  lines.push('', `<sub>${t.footer(args.model, cost)}</sub>`, `<!-- ${MARKER}:sha=${args.headSha} -->`);
  return lines.join('\n');
}

/** Head SHA recorded by the previous review of this bot, for incremental runs. */
export function lastReviewedSha(bodies: string[]): string | null {
  for (let i = bodies.length - 1; i >= 0; i--) {
    const m = new RegExp(`<!-- ${MARKER}:sha=([0-9a-f]{40}) -->`).exec(bodies[i] ?? '');
    if (m) return m[1]!;
  }
  return null;
}
